// monta um MX_MOD novo a partir do que foi forjado no launcher
function mxBuildKitMod(info) {
  const kit = MX_KITS[info.kit] || MX_KITS.blank;
  const modId = info.modId || 'meu_mod';
  return JSON.parse(JSON.stringify({
    modName: info.name || 'Meu Mod',
    modId,
    modVersion: '0.1.0',
    author: '',
    emblem: info.emblem || '',
    neoforge: '26.1.4',
    folder: `~/mods/${modId.replace(/_/g, '-')}`,
    description: '',
    items: kit.items, blocks: kit.blocks, recipes: kit.recipes,
  }));
}

